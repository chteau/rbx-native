//! Packs the Studio plugin's Luau sources into an installable `.rbxmx`.
//!
//! The plugin is one `Script` whose children are the other modules, so the
//! file can be dropped into Studio's plugins folder as is.

use std::error::Error;
use std::fs;
use std::path::{Path, PathBuf};

use rbx_dom::{Variant, WeakDom};

const MAIN_FILE: &str = "TeamPresence.server.luau";
const SOURCE_OPEN: &str = "<string name=\"Source\">";
const SOURCE_CLOSE: &str = "</string>";

/// The generated `Defaults` module: the community fallback used when the
/// place names no relay, written from the one Rust source of truth so the
/// plugin and the editor can never disagree on it. A URL, a kind word and
/// the label hold no `"` or `\`, so plain quoting is safe here.
fn defaults_source() -> String {
    format!(
        "--!strict\n-- Generated by build_presence_plugin; do not edit.\nreturn {{\n\tcommunityUrl = \"{}\",\n\tcommunityKind = \"{}\",\n\tcommunityLabel = \"{}\",\n}}\n",
        rbx_presence::relay::COMMUNITY_URL,
        rbx_presence::relay::COMMUNITY_KIND.as_str(),
        rbx_presence::relay::COMMUNITY_LABEL,
    )
}

/// rbx-native's default theme, which the plugin's UI is drawn in so it looks
/// like the editor's own docks.
fn theme_path() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/themes/default/theme.json")
}

/// One theme colour as `(r, g, b, alpha)`, alpha 0–1. Values are `#RRGGBB`,
/// `#RRGGBBAA`, `@name` (another colour) or `@name/0.12` (another colour at
/// that opacity).
fn resolve_color(
    name: &str,
    colors: &serde_json::Map<String, serde_json::Value>,
    depth: usize,
) -> Option<(u8, u8, u8, f64)> {
    let raw = colors.get(name)?.as_str()?;
    if depth > 8 {
        return None;
    }
    if let Some(reference) = raw.strip_prefix('@') {
        let (target, alpha) = match reference.split_once('/') {
            Some((target, alpha)) => (target, Some(alpha.parse::<f64>().ok()?)),
            None => (reference, None),
        };
        let (r, g, b, a) = resolve_color(target, colors, depth + 1)?;
        return Some((r, g, b, alpha.unwrap_or(a)));
    }
    let hex = raw.strip_prefix('#')?;
    let byte = |i: usize| u8::from_str_radix(hex.get(i..i + 2)?, 16).ok();
    let alpha = match hex.len() {
        6 => 1.0,
        8 => f64::from(byte(6)?) / 255.0,
        _ => return None,
    };
    Some((byte(0)?, byte(2)?, byte(4)?, alpha))
}

/// The generated `Theme` module: every colour and size of rbx-native's
/// default theme, so the plugin cannot drift from the editor's look.
fn theme_source(json: &str) -> Result<String, Box<dyn Error>> {
    let theme: serde_json::Value = serde_json::from_str(json)?;
    let colors = theme
        .get("colors")
        .and_then(|c| c.as_object())
        .ok_or("theme.json: no colors")?;
    let mut out = String::from(
        "--!strict\n-- Generated by build_presence_plugin from assets/themes/default/theme.json; do not edit.\n-- Colours are { r, g, b, alpha } with r, g, b in 0-255 and alpha in 0-1.\nreturn {\n\tcolors = {\n",
    );
    let mut names: Vec<&String> = colors.keys().collect();
    names.sort();
    for name in names {
        if let Some((r, g, b, a)) = resolve_color(name, colors, 0) {
            out.push_str(&format!("\t\t{name} = {{ {r}, {g}, {b}, {a:.3} }},\n"));
        }
    }
    out.push_str("\t},\n\tsizes = {\n");
    if let Some(sizes) = theme.get("sizes").and_then(|s| s.as_object()) {
        let mut names: Vec<&String> = sizes.keys().collect();
        names.sort();
        for name in names {
            if let Some(value) = sizes[name].as_f64() {
                out.push_str(&format!("\t\t{name} = {value},\n"));
            }
        }
    }
    out.push_str("\t},\n}\n");
    Ok(out)
}

const LUAU_KEYWORDS: &[&str] = &[
    "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local",
    "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
];

/// A table key: bare when it is a Luau identifier, else `["..."]`.
fn luau_key(name: &str) -> String {
    let mut chars = name.chars();
    let ident = chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !LUAU_KEYWORDS.contains(&name);
    if ident {
        name.to_string()
    } else {
        format!("[{}]", luau_string(name))
    }
}

fn luau_string(text: &str) -> String {
    let mut out = String::from("\"");
    for c in text.chars() {
        match c {
            '"' | '\\' => {
                out.push('\\');
                out.push(c);
            }
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// The generated `CoeditClasses` module: every class's own scriptable,
/// savable properties and their value types, which the co-editing code reads
/// to describe a new instance on the wire.
fn classes_source() -> String {
    const SKIPPED_TAGS: &[&str] = &[
        "ReadOnly",
        "NotScriptable",
        "Deprecated",
        "Hidden",
        "NotBrowsable",
    ];
    const SKIPPED_NAMES: &[&str] = &["Parent", "Name", "Archivable"];
    let db = rbx_reflection::ReflectionDatabase::shared();
    let mut names: Vec<&str> = db.class_names().collect();
    names.sort_unstable();
    let mut out = String::from(
        "--!strict\n-- Generated by build_presence_plugin from the Roblox API dump; do not edit.\nreturn {\n",
    );
    for name in names {
        let Some(class) = db.class(name) else {
            continue;
        };
        let mut props: Vec<(&str, &str)> = class
            .properties
            .iter()
            .filter(|p| {
                (p.can_save || p.can_load || !p.tags.is_empty() || p.category != "Data")
                    && !SKIPPED_NAMES.contains(&p.name.as_str())
                    && !p.tags.iter().any(|t| SKIPPED_TAGS.contains(&t.as_str()))
            })
            .map(|p| (p.name.as_str(), p.value_type.as_str()))
            .collect();
        props.sort_unstable();
        props.dedup_by_key(|p| p.0);
        out.push_str(&format!("\t{} = {{", luau_key(name)));
        if let Some(sup) = &class.superclass {
            out.push_str(&format!(" s = {},", luau_string(sup)));
        }
        out.push_str(" p = {\n");
        for (prop, ty) in props {
            out.push_str(&format!("\t\t{} = {},\n", luau_key(prop), luau_string(ty)));
        }
        out.push_str("\t} },\n");
    }
    out.push_str("}\n");
    out
}

fn plugin_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../../plugins/team-presence")
}

fn build(src_dir: &Path) -> Result<String, Box<dyn Error>> {
    let mut modules: Vec<(String, String)> = Vec::new();
    for entry in fs::read_dir(src_dir)? {
        let path = entry?.path();
        let Some(file_name) = path.file_name().and_then(|n| n.to_str()) else {
            continue;
        };
        if file_name == MAIN_FILE || path.extension().and_then(|e| e.to_str()) != Some("luau") {
            continue;
        }
        let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
            continue;
        };
        modules.push((stem.to_string(), fs::read_to_string(&path)?));
    }
    modules.sort();

    // The default relay endpoint is written here from the one Rust constant,
    // so the plugin and the editor can never point at different relays.
    modules.push(("Defaults".to_string(), defaults_source()));
    modules.push((
        "Theme".to_string(),
        theme_source(&fs::read_to_string(theme_path())?)?,
    ));
    modules.push(("CoeditClasses".to_string(), classes_source()));
    modules.sort();

    let main_source = fs::read_to_string(src_dir.join(MAIN_FILE))?;
    let mut dom = WeakDom::new();
    let script = dom.new_instance("Script", "TeamPresence", None);
    dom.set_property(script, "Source", Variant::String(main_source))?;
    for (name, source) in modules {
        let module = dom.new_instance("ModuleScript", &name, Some(script));
        dom.set_property(module, "Source", Variant::String(source))?;
    }

    Ok(protect_sources(&rbx_xml::serialize(&dom)?))
}

/// Studio only loads script source from `ProtectedString` elements.
fn protect_sources(xml: &str) -> String {
    let mut out = String::with_capacity(xml.len() + 256);
    let mut rest = xml;
    while let Some(start) = rest.find(SOURCE_OPEN) {
        let body_start = start + SOURCE_OPEN.len();
        let Some(len) = rest[body_start..].find(SOURCE_CLOSE) else {
            break;
        };
        let body_end = body_start + len;
        out.push_str(&rest[..start]);
        out.push_str("<ProtectedString name=\"Source\">");
        out.push_str(&rest[body_start..body_end]);
        out.push_str("</ProtectedString>");
        rest = &rest[body_end + SOURCE_CLOSE.len()..];
    }
    out.push_str(rest);
    out
}

fn main() -> Result<(), Box<dyn Error>> {
    let plugin = plugin_dir();
    let out = match std::env::args_os().nth(1) {
        Some(arg) => PathBuf::from(arg),
        None => plugin.join("build/TeamPresence.rbxmx"),
    };
    let xml = build(&plugin.join("src"))?;
    if let Some(parent) = out.parent() {
        fs::create_dir_all(parent)?;
    }
    fs::write(&out, xml)?;
    println!("{}", out.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn output_round_trips_with_every_module() {
        let src = plugin_dir().join("src");
        let xml = build(&src).expect("build");
        assert!(!xml.contains(SOURCE_OPEN));
        assert!(xml.contains("<ProtectedString name=\"Source\">"));

        let dom = rbx_xml::deserialize(&xml).expect("deserialize");
        assert_eq!(dom.root_refs().len(), 1);
        let root = dom.get(dom.root_refs()[0]).expect("root");
        assert_eq!(root.class(), "Script");
        assert_eq!(root.name(), "TeamPresence");

        let mut expected = 0;
        for entry in fs::read_dir(&src).expect("read src") {
            let path = entry.expect("entry").path();
            let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
            if name == MAIN_FILE || !name.ends_with(".luau") {
                continue;
            }
            expected += 1;
            let stem = path.file_stem().and_then(|s| s.to_str()).unwrap();
            let child = root
                .children()
                .iter()
                .filter_map(|&r| dom.get(r))
                .find(|c| c.name() == stem)
                .unwrap_or_else(|| panic!("missing module {stem}"));
            assert_eq!(child.class(), "ModuleScript");
            let want = fs::read_to_string(&path).unwrap();
            match child.properties().get("Source") {
                Some(Variant::String(got)) => assert_eq!(got, &want, "{stem}"),
                other => panic!("{stem}: unexpected Source {other:?}"),
            }
        }

        // The generated Defaults module carries the baked relay URL.
        let defaults = root
            .children()
            .iter()
            .filter_map(|&r| dom.get(r))
            .find(|c| c.name() == "Defaults")
            .expect("generated Defaults module");
        assert_eq!(defaults.class(), "ModuleScript");
        match defaults.properties().get("Source") {
            Some(Variant::String(got)) => {
                assert!(got.contains(rbx_presence::relay::COMMUNITY_URL));
                assert!(got.contains(rbx_presence::relay::COMMUNITY_KIND.as_str()));
            }
            other => panic!("Defaults: unexpected Source {other:?}"),
        }
        expected += 1;

        // The generated Theme module carries rbx-native's palette.
        let theme = root
            .children()
            .iter()
            .filter_map(|&r| dom.get(r))
            .find(|c| c.name() == "Theme")
            .expect("generated Theme module");
        match theme.properties().get("Source") {
            Some(Variant::String(got)) => {
                assert!(got.contains("dock = { 18, 18, 19, 1.000 }"), "{got}");
                assert!(got.contains("check_on = { 108, 127, 219, 1.000 }"));
            }
            other => panic!("Theme: unexpected Source {other:?}"),
        }
        expected += 1;

        assert!(root
            .children()
            .iter()
            .filter_map(|&r| dom.get(r))
            .any(|c| c.name() == "CoeditClasses"));
        expected += 1;

        assert_eq!(root.children().len(), expected);
    }

    #[test]
    fn classes_module_lists_scriptable_properties() {
        let src = classes_source();
        assert!(src.starts_with("--!strict"));
        assert_eq!(src.matches('{').count(), src.matches('}').count());
        assert!(
            src.contains("\tBasePart = { s = \"PVInstance\", p = {\n"),
            "BasePart"
        );
        let base = src.split("\tBasePart = ").nth(1).unwrap();
        let base = base.split("\t} },").next().unwrap();
        assert!(base.contains("\t\tSize = \"Vector3\","));
        assert!(base.contains("\t\tAnchored = \"bool\","));
        assert!(base.contains("\t\tColor = \"Color3\","));
        assert!(src.contains("\tPart = { s = \"FormFactorPart\""));
        assert!(src.contains("\t\tSource = "));
        assert!(!src.contains("\t\tName = "));
        assert!(!src.contains("\t\tParent = "));
    }

    #[test]
    fn theme_references_and_alpha_resolve() {
        let json = r##"{"colors":{"a":"#6C7FDB","b":"@a/0.12","c":"@b","d":"#FFFFFF0F","e":"@nope"},"sizes":{"radius":5}}"##;
        let src = theme_source(json).unwrap();
        assert!(src.contains("a = { 108, 127, 219, 1.000 }"));
        assert!(src.contains("b = { 108, 127, 219, 0.120 }"));
        assert!(src.contains("c = { 108, 127, 219, 0.120 }"));
        assert!(src.contains("d = { 255, 255, 255, 0.059 }"));
        assert!(!src.contains("e = "));
        assert!(src.contains("radius = 5,"));
    }
}
