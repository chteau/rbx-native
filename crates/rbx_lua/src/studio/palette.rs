/// The colour for `name` under `modifier` (an `Enum.StudioStyleGuideModifier`
/// name) in Studio theme `theme` ("Light", or Dark for anything else), or
/// `None` for a colour Studio does not have.
pub(crate) fn color(theme: &str, name: &str, modifier: &str) -> Option<[u8; 3]> {
    let index = match modifier {
        "Selected" => 1,
        "Pressed" => 2,
        "Disabled" => 3,
        "Hover" => 4,
        _ => 0,
    };
    let table = if theme == "Light" { LIGHT } else { DARK };
    let found = table.binary_search_by(|(key, _)| key.cmp(&name)).ok()?;
    Some(table[found].1[index])
}
