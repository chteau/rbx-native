/// The colour for `name` under `modifier` (an `Enum.StudioStyleGuideModifier`
/// name), or `None` for a colour Studio does not have.
pub(super) fn dark(name: &str, modifier: &str) -> Option<[u8; 3]> {
    let index = match modifier {
        "Selected" => 1,
        "Pressed" => 2,
        "Disabled" => 3,
        "Hover" => 4,
        _ => 0,
    };
    let found = DARK.binary_search_by(|(key, _)| key.cmp(&name)).ok()?;
    Some(DARK[found].1[index])
}
