//! Runs the conformance suite in rbx_sim and prints it against the goldens
//! recorded from real Roblox. `--write <file>` also writes the table as
//! markdown (`docs/research/local-run/CONFORMANCE.md`).
//!
//! ```text
//! cargo run -p rbx_sim --example conformance -- --write docs/research/local-run/CONFORMANCE.md
//! ```

use std::sync::Arc;

use rbx_assets::{AssetFetcher, FetchError};
use rbx_cloud::Client;
use rbx_sim::conformance::{self, Row, TESTS};

/// Public animations (the default ones, the catalog's) over the anonymous
/// asset delivery route; they land in the asset cache for the next run.
struct Anonymous(Client);

impl AssetFetcher for Anonymous {
    fn fetch_id(&self, id: u64) -> Result<Vec<u8>, FetchError> {
        self.0
            .asset(id)
            .map(|c| c.bytes)
            .map_err(|err| FetchError::Other {
                id,
                message: err.to_string(),
            })
    }
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let mut write = None;
    let mut only: Vec<String> = Vec::new();
    let mut rest = args.iter();
    while let Some(arg) = rest.next() {
        match (arg.as_str(), rest.next()) {
            ("--write", Some(path)) => write = Some(path.clone()),
            ("--only", Some(names)) => only.extend(names.split(',').map(str::to_owned)),
            _ => {
                eprintln!("usage: conformance [--write <file.md>] [--only Test,Test]");
                std::process::exit(2);
            }
        }
    }
    let ours =
        conformance::run_some_in_sim(1200.0, &only, Some(Arc::new(Anonymous(Client::new(None)))))
            .unwrap_or_else(|err| {
                eprintln!("{err}");
                std::process::exit(1);
            });
    // `CONFORMANCE_DUMP=<dir>` keeps what we measured, one JSON per test
    // (the easing plots are drawn from it).
    if let Some(dir) = std::env::var_os("CONFORMANCE_DUMP") {
        for (name, value) in &ours {
            let path = std::path::Path::new(&dir).join(format!("{name}.json"));
            if let Err(err) = std::fs::write(&path, value.to_string()) {
                eprintln!("{}: {err}", path.display());
            }
        }
    }
    let mut table =
        String::from("| Test | Field | Roblox | rbx_sim | Delta | |\n|---|---|---|---|---|---|\n");
    let mut unrecorded = Vec::new();
    let mut gaps = Vec::new();
    for test in TESTS
        .iter()
        .filter(|t| only.is_empty() || only.iter().any(|n| n == t.name))
    {
        let mine = ours.get(test.name).cloned().unwrap_or_default();
        let Some(golden) = conformance::golden(test.name).filter(|g| g["status"] == "recorded")
        else {
            unrecorded.push(test.name);
            println!("{}: no golden recorded; ours: {mine}", test.name);
            continue;
        };
        if let Some(gap) = golden["known_gap"].as_str() {
            gaps.push(format!("- **{}**: {gap}", test.name));
        }
        for row in conformance::compare(test, &golden, &mine) {
            if let (false, Some(gap)) = (row.pass, &row.gap) {
                gaps.push(format!("- **{}.{}**: {gap}", row.test, row.field));
            }
            println!(
                "{:<16} {:<20} roblox {:<14} ours {:<14} {}",
                row.test,
                row.field,
                row.golden,
                row.ours,
                mark(&row)
            );
            table.push_str(&format!(
                "| {} | {} | {} | {} | {} | {} |\n",
                row.test,
                row.field,
                cell(&row.golden),
                cell(&row.ours),
                row.delta.map_or(String::new(), |d| format!("{d:+.3}")),
                mark(&row)
            ));
        }
    }
    if let Some(path) = write {
        let mut text = String::from(
            "# Local Run conformance\n\nGenerated by `cargo run -p rbx_sim --example conformance -- --write docs/research/local-run/CONFORMANCE.md`. \
             Roblox is the golden recorded from a real server (`crates/rbx_sim/conformance/goldens/`), rbx_sim is this build. \
             Roblox's value is the median over the recorded passes. A number passes when the delta is inside the test's \
             tolerance (`rbx_sim::conformance::TESTS`) or Roblox's own spread across passes, whichever is wider; text must match the common value or one a pass printed. \
             `ok (pass N)` means the median check failed but the value is within tolerance of recorded pass N: the real server is not deterministic \
             (its first passes often take extra substeps on a test's first frames), and rbx_sim models the clean passes.\n\n",
        );
        text.push_str(&table);
        if !gaps.is_empty() {
            text.push_str(&format!("\nKnown gaps:\n\n{}\n", gaps.join("\n")));
        }
        if !unrecorded.is_empty() {
            text.push_str(&format!(
                "\nNo golden recorded yet: {}.\n",
                unrecorded.join(", ")
            ));
        }
        std::fs::write(&path, text).unwrap_or_else(|err| {
            eprintln!("{path}: {err}");
            std::process::exit(1);
        });
    }
}

fn mark(row: &Row) -> String {
    match (row.pass, row.matched_pass) {
        (true, Some(pass)) => format!("ok (pass {pass})"),
        (true, None) => "ok".into(),
        (false, _) if row.gap.is_some() => "known gap".into(),
        (false, _) => "off".into(),
    }
}

fn cell(text: &str) -> String {
    format!("`{}`", text.replace('|', "\\|"))
}
